#!/usr/bin/env node
// Picks the deals of the monthly tower ("Turmbau zu Babel", game/BabelSeeds.js):
// per month and stage the first candidate seed that the "hard" heuristic in the
// human seat beats against that stage's bots (BotTower ladder), Zen on the net.
// Run with onnxruntime-node installed OUTSIDE the repo (CLAUDE.md), e.g.
//   NODE_PATH=/path/ort/node_modules node scripts/tower-seeds.js 2026-10 2027-12
// Rewrites game/BabelSeeds.js; the per-stage margins go to stderr.
'use strict';
const GameManager = require('../game/GameManager');
const BotTower = require('../game/BotTower');
const OnnxPolicy = require('../game/OnnxPolicy');
const fs = require('fs');
const path = require('path');

const RUNS = 3; // a seed passes with stars in 2 of 3 runs (bots may vary)
// Late stages must stay tight: the median margin may not exceed this cap.
const marginCap = (stage) => 260 - 20 * stage; // stage 10: 60

function monthsBetween(from, to) {
  const out = [];
  let [y, m] = from.split('-').map(Number);
  const [ty, tm] = to.split('-').map(Number);
  while (y < ty || (y === ty && m <= tm)) {
    out.push(`${y}-${String(m).padStart(2, '0')}`);
    m += 1;
    if (m > 12) { m = 1; y += 1; }
  }
  return out;
}

/** One play of `seed` as tower stage `stage`: the human seat plays "hard". */
async function playOnce(seed, stage) {
  const g = new GameManager(() => {}, { deckSeed: seed, towerStage: stage });
  g.addOrReconnectPlayer('me', 'Sim');
  g.syncLobbyBots();
  if (g.startTowerRound().error) throw new Error(`stage ${stage} did not start`);
  g.players.find((p) => p.id === 'me').botDifficulty = 'hard';
  let guard = 0;
  while (g.phase === 'playing' && guard++ < 5000) {
    const cp = g.currentPlayer();
    const before = g.turnIndexInRound;
    if (cp.isBot && g._botTurnUsesOnnx(cp)) await g._runBotTurnWithOnnx(cp.id);
    else g.runBotTurn(cp.id, { forced: !cp.isBot });
    if (g.phase === 'playing' && g.turnIndexInRound === before && g.currentPlayer().id === cp.id) g.finishRound(null);
  }
  const record = g.lastGameRecord || null;
  const totals = { ...(g.totals || {}) };
  g.destroy();
  if (record && record.towerStage) return BotTower.outcomeFromRecord(record, 'me');
  // Fallback: grade from the totals of the one round.
  const cfg = BotTower.stageConfig(stage);
  const botScores = Object.entries(totals).filter(([id]) => id !== 'me').map(([, v]) => v);
  const best = botScores.length ? Math.max(...botScores) : 0;
  return { margin: (totals.me || 0) - cfg.handicap - best, stars: BotTower.starsFor({ myScore: totals.me || 0, botScores, wentOut: false, handicap: cfg.handicap }) };
}

async function judge(seed, stage) {
  const margins = [];
  let wins = 0;
  for (let i = 0; i < RUNS; i++) {
    const o = await playOnce(seed, stage);
    margins.push(o.margin);
    if (o.stars >= 1) wins += 1;
    if (wins >= 2 || i - wins >= RUNS - 2) break; // decided early
  }
  margins.sort((a, b) => a - b);
  const median = margins[Math.floor(margins.length / 2)];
  return { ok: wins >= 2 && median <= marginCap(stage), wins, median };
}

async function main() {
  const [from = '2026-10', to = '2027-12'] = process.argv.slice(2);
  process.stderr.write(`net ${OnnxPolicy.enabled() ? 'ON' : 'OFF'}\n`);
  if (!OnnxPolicy.enabled()) process.stderr.write('WARNING: Zen falls back to the heuristic - seeds are not prod-calibrated\n');
  const used = new Set(BotTower.TOWER_STAGES.map((s) => s.seed));
  const out = {};
  let next = 1000; // fixed-tower seeds are < 1000; one running counter keeps it reproducible
  for (const month of monthsBetween(from, to)) {
    out[month] = [];
    for (let stage = 1; stage <= BotTower.TOWER_SIZE; stage++) {
      for (let tries = 0; ; tries++) {
        const seed = next++;
        if (used.has(seed)) continue;
        const v = await judge(seed, stage);
        if (v.ok) {
          used.add(seed);
          out[month].push(seed);
          process.stderr.write(`${month} stage ${stage}: seed ${seed} (wins ${v.wins}, median margin ${v.median}, ${tries + 1} candidates)\n`);
          break;
        }
      }
    }
  }
  const lines = Object.entries(out).map(([m, seeds]) => `  '${m}': [${seeds.join(', ')}],`).join('\n');
  fs.writeFileSync(path.join(__dirname, '..', 'game', 'BabelSeeds.js'), `${HEADER}module.exports = {\n${lines}\n};\n`);
}

const HEADER = `// game/BabelSeeds.js - generated by scripts/tower-seeds.js, do not edit.
// The deals of the monthly tower (Turmbau zu Babel): the hard heuristic in the
// human seat beats each stage's bots (Zen on the net) and late stages stay
// tight. Data only; the rules live in BotTower.js. Later months cycle.
`;

main().catch((e) => { console.error(e); process.exit(1); });
